export interface PicSizesModule {
  FRLG: PicSizeTable;
  fromPack(pack: any): PicSizeTable;
  active(): PicSizeTable;
  reset(): void;
  readonly front: Record<number, number>;
  readonly back: Record<number, number>;
  [k: string]: any;
}

export const PicSizes = { FRLG } as PicSizesModule;
let packs: Record<string, PicSizeTable> = {};

// Lua: g1_pic_sizes.lua:838
PicSizes.fromPack = function (pack: any): PicSizeTable {
  const isT = (v: any) => v != null && typeof v === "object";
  if (!isT(pack) || !isT(pack.front) || !isT(pack.back)) {
    throw new Error("pic_sizes: pack is missing front/back");
  }
  const out: PicSizeTable = { front: {}, back: {} };
  for (const [sp, row] of pairs<any>(pack.front)) out.front[sp as number] = row.width * 256 + row.height;
  for (const [sp, row] of pairs<any>(pack.back)) out.back[sp as number] = row.width * 256 + row.height;
  return out;
};

// Lua: g1_pic_sizes.lua:848
PicSizes.active = function (): PicSizeTable {
  if (Profile.family() === "frlg") return FRLG;
  const key = GameVersion.get() + ":" + tostring(GameVersion.cachePrefix());
  let hit = packs[key];
  if (hit) return hit;
  const src = Dataset.cache().read(PicCoords.PACK);
  if (typeof src !== "string") {
    throw new Error("pic_sizes: " + PicCoords.PACK + " missing from the " + GameVersion.get() + " cache");
  }
  const [chunk, err] = luaLoad(src, "@" + PicCoords.PACK);
  if (!truthy(chunk)) throw new Error("pic_sizes: " + tostring(err));
  hit = PicSizes.fromPack((chunk as () => any)());
  packs[key] = hit;
  return hit;
};

// Lua: g1_pic_sizes.lua:866
PicSizes.reset = function (): void {
  packs = {};
};

// Lua: g1_pic_sizes.lua:870 (setmetatable __index)
for (const k of ["front", "back"] as const) {
  Object.defineProperty(PicSizes, k, { get: () => PicSizes.active()[k], enumerable: true });
}

export default PicSizes;
