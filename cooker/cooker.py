def removable_drives():
    """[(root, looks_like_3ds_card)] for every removable volume we can see."""
    found = []
    os_name, _ = platform_key()
    if os_name == "windows":
        import ctypes
        import string
        mask = ctypes.windll.kernel32.GetLogicalDrives()
        for i, letter in enumerate(string.ascii_uppercase):
            if not (mask >> i) & 1:
                continue
            root = f"{letter}:\\"
            if ctypes.windll.kernel32.GetDriveTypeW(root) == 2:  # DRIVE_REMOVABLE
                found.append(root)
    elif os_name == "darwin":
        for v in Path("/Volumes").iterdir():
            if v.is_dir() and os.path.ismount(v) and not os.path.samefile(v, "/"):
                found.append(str(v))
    else:
        for base in (Path("/media"), Path("/run/media")):
            if not base.exists():
                continue
            for user in base.iterdir():
                for v in user.iterdir() if user.is_dir() else []:
                    if v.is_dir() and os.path.ismount(v):
                        found.append(str(v))
    return [(root, (Path(root) / "3ds").is_dir()) for root in found]


def copy_tree_with_progress(src, dst, label):
    files = [p for p in Path(src).rglob("*") if p.is_file()]
    total = sum(p.stat().st_size for p in files)
    done = 0
    for i, p in enumerate(files, 1):
        rel = p.relative_to(src)
        target = Path(dst) / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(p, target)
        done += p.stat().st_size
        print(f"  {label}: {i}/{len(files)} files, {mb(done)} of {mb(total)}", end="\r", flush=True)
    print(" " * 70, end="\r")
    say(f"  {label}: {len(files)} files, {mb(total)}")


def install_to_card(root, card_dir):
    """Merge output/3ds into <root>/3ds the way the docs say to."""
    dest = Path(root) / "3ds"
    paks = dest / "voxelmon" / "paks"
    # The paks, gamedata.json, common.vxat and index.txt are ONE artifact:
    # clear the old set first so nothing from a previous build survives
    # beside the new one. save.lua lives one folder up and is untouched.
    if paks.exists():
        for p in paks.iterdir():
            if p.is_file():
                p.unlink()
    copy_tree_with_progress(card_dir, dest, "copying to the card")
    say(f"  done: {dest}")


