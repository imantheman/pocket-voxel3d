#!/usr/bin/env python3
"""Pocket Voxel cooker: drop your Pokemon Red ROM on it, get an SD card folder.

    Windows:  drag your .gb file onto "Cook Pocket Voxel.bat"
    Mac:      double-click "Cook Pocket Voxel.command", then drag the .gb
              file into the window it opens and press Return
    Linux:    ./cook.sh /path/to/PokemonRed.gb

Everything this does is in this one file, on purpose, so that anyone can
read it before they run it. There is no installer and nothing is written
outside this folder: tools go in `_work/`, the result goes in `output/`.
Delete the folder and the machine is exactly as it was.

What it does, in order:

  1. Checks the ROM is the real US Pokemon Red (by SHA-1) and refuses
     anything else. The ROM never leaves your machine and nothing from it
     is in this folder or on GitHub -- that is the whole point of cooking
     on YOUR computer.
  2. Shows you exactly what it wants to download (the Bun runtime the game
     tools run on, the game's own source, and three data files from the
     projects it builds on), with the URL and license of each, and asks.
     Every download is checked against a checksum pinned below.
  3. Asks whether you want colour. Pokemon Red is a black-and-white game;
     the colour comes from a community colourisation (pokered-gbc), and it
     is your call whether to use it.
  4. Runs the importer (your ROM -> data, seconds) and the cooker (data ->
     222 map paks, two to fifteen minutes depending on the machine).
  5. Puts the finished `3ds` folder in `output/`, writes `SOURCES.txt`
     beside it listing everything that went in, and offers to copy it
     straight onto an SD card if it can see one.

Options, for people who want them:  --yes  (accept every default, no
questions)  --grayscale  --colour  --no-sd  --no-open  --rom PATH

Needs Python 3.8 or newer and an internet connection for the first run.
Budget up to 20 minutes, 3 GB of free disk while it runs, and 700 MB on the card.
"""
