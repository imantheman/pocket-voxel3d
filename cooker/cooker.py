def platform_key():
    system = platform.system()
    machine = platform.machine().lower()
    arch = "x64" if machine in ("amd64", "x86_64") else "aarch64" if machine in ("arm64", "aarch64") else machine
    os_name = {"Windows": "windows", "Linux": "linux", "Darwin": "darwin"}.get(system)
    if not os_name:
        die(f"unsupported operating system: {system}")
    return os_name, arch


def bun_path():
    os_name, _ = platform_key()
    return WORK / "bun" / ("bun.exe" if os_name == "windows" else "bun")


def bun_works(exe):
    try:
        r = subprocess.run([str(exe), "--version"], capture_output=True, text=True, timeout=30)
        return r.returncode == 0 and r.stdout.strip() != ""
    except (OSError, subprocess.SubprocessError):
        return False


def fetch_bun(variant):
    """variant: e.g. 'windows-x64' or 'windows-x64-baseline'."""
    if variant not in BUN_SHA256:
        die(f"no pinned Bun build for {variant}. Install Bun from https://bun.sh and put it on PATH.")
    url = f"https://github.com/oven-sh/bun/releases/download/bun-v{BUN_VERSION}/bun-{variant}.zip"
    z = download(url, WORK / f"bun-{variant}.zip", BUN_SHA256[variant], f"Bun {BUN_VERSION} ({variant})")
    target = WORK / "bun"
    shutil.rmtree(target, ignore_errors=True)
    target.mkdir(parents=True)
    with zipfile.ZipFile(z) as zf:
        for info in zf.infolist():
            name = Path(info.filename).name
            if info.is_dir() or name not in ("bun", "bun.exe"):
                continue
            with zf.open(info) as src, open(target / name, "wb") as dst:
                shutil.copyfileobj(src, dst)
    exe = bun_path()
    exe.chmod(exe.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    z.unlink()
    return exe


def ensure_bun():
    """Bun in _work/, or the one already on PATH if it is new enough."""
    exe = bun_path()
    if exe.exists() and bun_works(exe):
        return exe
    on_path = shutil.which("bun")
    if on_path and bun_works(on_path):
        say(f"  using the Bun already on this machine: {on_path}")
        return Path(on_path)
    os_name, arch = platform_key()
    exe = fetch_bun(f"{os_name}-{arch}")
    if not bun_works(exe):
        # Bun's main build wants a CPU with AVX2 (2013 and newer). Older ones
        # crash on the first instruction; the baseline build runs anywhere.
        say("  that Bun build will not start on this CPU; fetching the baseline build")
        exe = fetch_bun(f"{os_name}-{arch}-baseline")
        if not bun_works(exe):
            die("Bun will not run on this machine.")
    return exe


def ensure_repo():
    """The game's source: the checkout this file lives in, or a fetched zip."""
    checkout = HERE.parent
    if (checkout / "tools" / "cook3ds.ts").exists():
        return checkout, "the checkout this cooker is part of"
    repo = WORK / "pocket-voxel"
    if (repo / "tools" / "cook3ds.ts").exists():
        return repo, f"{POCKET_VOXEL_REPO} @ {POCKET_VOXEL_REF} (already fetched)"
    # (POCKET_VOXEL_ZIP in the environment names another zip -- a file://
    # one, say -- which is how the repository's tests exercise this path.)
    url = os.environ.get("POCKET_VOXEL_ZIP") or f"https://github.com/{POCKET_VOXEL_REPO}/archive/{POCKET_VOXEL_REF}.zip"
    z = download(url, WORK / "pocket-voxel.zip", None, f"pocket-voxel source ({POCKET_VOXEL_REF})")
    shutil.rmtree(repo, ignore_errors=True)
    with zipfile.ZipFile(z) as zf:
        top = {n.split("/", 1)[0] for n in zf.namelist()}
        if len(top) != 1:
            die("the source zip does not have the shape a GitHub archive has")
        zf.extractall(WORK)
    (WORK / top.pop()).rename(repo)
    z.unlink()
    return repo, f"{POCKET_VOXEL_REPO} @ {POCKET_VOXEL_REF}"


def data_file_path(key):
    folder, rel, _, _, _, _ = DATA_FILES[key]
    return WORK / folder / rel


def data_file_url(key):
    _, rel, (repo, commit), _, _, _ = DATA_FILES[key]
    return f"https://raw.githubusercontent.com/{repo}/{commit}/{rel}"


def ensure_data_file(key):
    path = data_file_path(key)
    _, rel, _, sha, _, _ = DATA_FILES[key]
    if path.exists() and sha256_of(path) == sha:
        return path
    return download(data_file_url(key), path, sha, rel)


