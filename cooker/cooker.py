def say(*parts):
    """Print, and keep a copy in _work/cooker.log for when something goes wrong."""
    line = " ".join(str(p) for p in parts)
    print(line, flush=True)
    if _log:
        _log.write(line + "\n")
        _log.flush()


def die(*parts):
    say()
    say("STOPPED:", *parts)
    say(f"(the full log is in {LOG})")
    sys.exit(1)


def ask(question, default_yes=True, yes_to_all=False):
    if yes_to_all:
        say(f"{question} [{'Y/n' if default_yes else 'y/N'}] -> {'y' if default_yes else 'n'} (--yes)")
        return default_yes
    try:
        answer = input(f"{question} [{'Y/n' if default_yes else 'y/N'}] ").strip().lower()
    except EOFError:
        answer = ""
    if _log:
        _log.write(f"{question} -> {answer or '(default)'}\n")
    if not answer:
        return default_yes
    return answer[0] == "y"


def mb(n):
    return f"{n / 1024 / 1024:.1f} MB"


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def sha1_of(path):
    h = hashlib.sha1()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def download(url, dest, sha256=None, label=None):
    """Fetch url to dest with a progress line; verify the checksum if given."""
    dest = Path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    label = label or dest.name
    part = dest.with_suffix(dest.suffix + ".part")
    say(f"  fetching {label}")
    say(f"    {url}")
    req = urllib.request.Request(url, headers={"User-Agent": "pocket-voxel-cooker"})
    with urllib.request.urlopen(req, timeout=60) as r, open(part, "wb") as f:
        total = int(r.headers.get("Content-Length") or 0)
        got = 0
        last = -1
        while True:
            chunk = r.read(1 << 16)
            if not chunk:
                break
            f.write(chunk)
            got += len(chunk)
            if total:
                pct = got * 100 // total
                if pct // 10 != last // 10:
                    print(f"    {pct:3d}%  {mb(got)} of {mb(total)}", end="\r", flush=True)
                    last = pct
        print(" " * 60, end="\r")
    if sha256:
        actual = sha256_of(part)
        if actual != sha256:
            part.unlink()
            die(f"{label} did not match its pinned checksum.",
                f"\n  expected {sha256}\n  got      {actual}",
                "\nThe download may be corrupt, or the file at that URL changed. Nothing was kept.")
    part.replace(dest)
    say(f"    ok, {mb(dest.stat().st_size)}" + (", checksum verified" if sha256 else ""))
    return dest


