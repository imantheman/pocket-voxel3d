// Writes voxelmon/game/vc/eventflags.ts: the cartridge save's event-flag
// bit numbers, by the EVENT_* names this game's scripts use.
//
//   bun tools/vc_eventflags.ts [gen1recomp checkout]
//
// The names and numbers are gen1recomp's src/save_convert/data/
// event_flags.lua and event_flags_yellow.lua at the MIT-licensed pin
// 943ba5dc (Copyright 2026 BOIS CLUB GAMES, LLC; see THIRD_PARTY_NOTICES.md)
// -- the same names this port's scripts were ported with. Only that pin may
// be used: later gen1recomp commits are under a different licence.

import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const PIN = "943ba5dc";
const dir = process.argv[2] ?? process.env.VOXELMON_G1R ?? join(homedir(), "gen1recomp");
const head = execSync("git rev-parse HEAD", { cwd: dir }).toString().trim();
if (!head.startsWith(PIN)) {
  console.error(`vc_eventflags: ${dir} is at ${head.slice(0, 8)}, not the MIT pin ${PIN}`);
  process.exit(1);
}

function table(file: string): string {
  const src = readFileSync(join(dir, "src/save_convert/data", file), "utf8").split("byName")[0]!;
  const rows = [...src.matchAll(/\[(\d+)\] = "(\w+)"/g)].map((m) => [Number(m[1]), m[2]!] as const);
  rows.sort((a, b) => a[0] - b[0]);
  // "bit name" pairs, space separated: compact in the bundle, trivial to split
  return rows.map(([b, n]) => `${b} ${n.replace(/^EVENT_/, "")}`).join(" ");
}

const out = `// Generated by tools/vc_eventflags.ts -- do not edit.
//
// The cartridge save's event flags (wEventFlags, 2560 bits, bit N in byte
// N/8 at mask 1 << (N % 8)) by the EVENT_* names this port's scripts use,
// without the EVENT_ prefix: "<bit> <name>" pairs.
//
// From gen1recomp src/save_convert/data/event_flags.lua and
// event_flags_yellow.lua at the MIT-licensed pin ${PIN}
// (Copyright 2026 BOIS CLUB GAMES, LLC; MIT, see THIRD_PARTY_NOTICES.md).

export const EVENT_FLAGS_RB = ${JSON.stringify(table("event_flags.lua"))};

export const EVENT_FLAGS_YELLOW = ${JSON.stringify(table("event_flags_yellow.lua"))};
`;
const path = join(import.meta.dir, "../voxelmon/game/vc/eventflags.ts");
writeFileSync(path, out);
console.log(`vc_eventflags: wrote ${path}`);
